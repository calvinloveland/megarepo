//
// Hand-authored character grids live here rather than beside the drawing code
// so the tables can be read (and checked) as tables: every row is exactly 16
// cells — one tile — and every non-blank cell is a palette key. A row that is
// a cell short leaves a hole in a face, which is a miserable thing to find by
// eye in a 32px sprite.

