export function isTilePassable(tile: TileKind): boolean {
  return (
    tile === "path" ||
    tile === "grass" ||
    tile === "vroomgrass" ||
    tile === "indoor-floor" ||
    tile === "doormat" ||
    tile === "tall-grass-edge" ||
    tile === "counter" ||
    tile === "rock"
  );
}
