/*
 * Bot bundler.
 *
 * A submitted bot has to be a SINGLE ES module (PROTOCOL.md §8), but both of
 * ours share a brain. So the shared brain lives in bots/src/core.js and this
 * script inlines it into each strategy, stripping module syntax. No dependency,
 * no build tool: the output is plain ES2019 that the Arena's sandbox can run.
 *
 *   node scripts/build-bots.mjs           # write bots/dist/*.js
 *   node scripts/build-bots.mjs --check   # fail if dist/ is stale (for checks)
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'bots', 'src');
const DIST = path.join(ROOT, 'bots', 'dist');

const BOTS = [
  { name: 'boiler-stoker', strategy: 'score.js', title: 'Boiler Stoker (score maximiser)' },
  { name: 'four-line-fanatic', strategy: 'hunter.js', title: 'Four-Line Fanatic (Tetris hunter)' },
];

const HEADER = `/*
 * %TITLE%
 * Tetris Protocol v2 bot — single-file bundle, generated by scripts/build-bots.mjs.
 * Author: Calvin Loveland (agent: deepseek)
 * Do not edit here: edit bots/src/*.js and re-run the bundler.
 */
`;

/** Remove module syntax so the files can be concatenated into one module. */
function strip(text) {
  return text
    .replace(/^import\s[^\n]*\n/gm, '')
    .replace(/^export\s+default\s+[A-Za-z_$][\w$]*;?\s*\n/gm, '')
    .replace(/^export\s+default\s+/gm, '')
    .replace(/^export\s+/gm, '');
}

function bundle(bot) {
  const core = strip(fs.readFileSync(path.join(SRC, 'core.js'), 'utf8'));
  const strategy = strip(fs.readFileSync(path.join(SRC, bot.strategy), 'utf8'));
  const header = HEADER.replace('%TITLE%', bot.title);
  return `${header}\n${core}\n${strategy}\nexport default bot;\n`;
}

const check = process.argv.includes('--check');
let stale = 0;

fs.mkdirSync(DIST, { recursive: true });
for (const bot of BOTS) {
  const code = bundle(bot);
  const target = path.join(DIST, `${bot.name}.js`);
  const previous = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (check) {
    if (previous !== code) {
      console.error(`stale bundle: bots/dist/${bot.name}.js (run: npm run bots:build)`);
      stale += 1;
    }
    continue;
  }
  fs.writeFileSync(target, code);
  const lines = code.split('\n').length;
  const changed = previous === code ? 'unchanged' : 'written';
  console.log(`bots/dist/${bot.name}.js — ${lines} lines, ${(code.length / 1024).toFixed(1)} KiB (${changed})`);
}

if (check) {
  if (stale) process.exit(1);
  console.log('bot bundles are up to date');
}
