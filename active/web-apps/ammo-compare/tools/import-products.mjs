/**
 * Import a product catalog export into `data/products.js`.
 *
 * The app never fetches anything, and neither does this tool: you hand it a file
 * you already have — a manufacturer spec sheet exported to CSV, a retailer
 * listing export, a spreadsheet — and it validates, derives, and writes the
 * checked-in catalog. That keeps "actually for sale" honest: a price only exists
 * because a listing was captured, and every row says where it came from.
 *
 * Usage:
 *   node tools/import-products.mjs catalog.csv            # validate + write
 *   node tools/import-products.mjs catalog.csv --check    # exit 1 if stale
 *   node tools/import-products.mjs catalog.json --dry-run # summary only
 *
 * CSV columns (header row required, unknown columns ignored):
 *   id, cartridge, brand, line, sku, bulletGr, bulletType, packageRounds,
 *   velocityFps, priceUsd, priceSource, priceChecked, source, sourceUrl, note
 *
 * `cartridge` is an id from `data/ammo.js` (e.g. `9mm`, `380acp`, `308`).
 * Prices are for the whole box; `packageRounds` is the box size.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { PRODUCTS, PRODUCT_SCHEMA_VERSION, PACKAGE_SIZES, validateProducts } from '../lib/products.js';

const OUT = new URL('../data/products.js', import.meta.url);
const NUMERIC = new Set(['bulletGr', 'packageRounds', 'velocityFps', 'priceUsd']);
const KNOWN = new Set([
  'id',
  'cartridge',
  'brand',
  'line',
  'sku',
  'bulletGr',
  'bulletType',
  'packageRounds',
  'velocityFps',
  'velocitySource',
  'priceUsd',
  'priceSource',
  'priceChecked',
  'source',
  'sourceUrl',
  'note',
  'pelletLabel',
]);

/** Split one CSV line, honouring double quotes and doubled quotes. */
function splitCsvLine(line) {
  const cells = [];
  let cell = '';
  let quoted = false;
  for (let i = 0; i < line.length; i += 1) {
    const character = line[i];
    if (quoted) {
      if (character === '"' && line[i + 1] === '"') {
        cell += '"';
        i += 1;
      } else if (character === '"') {
        quoted = false;
      } else {
        cell += character;
      }
      continue;
    }
    if (character === '"') quoted = true;
    else if (character === ',') {
      cells.push(cell);
      cell = '';
    } else cell += character;
  }
  cells.push(cell);
  return cells.map((value) => value.trim());
}

function fromCsv(text) {
  const lines = text.split(/\r?\n/).filter((line) => line.trim() && !line.startsWith('#'));
  if (lines.length === 0) return [];
  const header = splitCsvLine(lines[0]);
  return lines.slice(1).map((line) => {
    const cells = splitCsvLine(line);
    const row = {};
    header.forEach((key, index) => {
      const value = cells[index];
      if (value === undefined || value === '') return;
      row[key] = value;
    });
    return row;
  });
}

function coerce(row) {
  const product = {};
  for (const [key, value] of Object.entries(row)) {
    if (!KNOWN.has(key)) continue;
    if (value === '' || value == null) continue;
    if (NUMERIC.has(key)) {
      const number = Number(value);
      product[key] = Number.isFinite(number) ? number : value;
    } else {
      product[key] = value;
    }
  }
  // A published velocity is only "published" if the file says so.
  if (product.velocityFps != null && !product.velocitySource) {
    product.velocitySource = 'manufacturer';
  }
  return product;
}

function readCatalog(path) {
  const text = readFileSync(path, 'utf8');
  const rows = path.endsWith('.json')
    ? (() => {
        const parsed = JSON.parse(text);
        return Array.isArray(parsed) ? parsed : (parsed.products ?? []);
      })()
    : fromCsv(text);
  return rows.map(coerce);
}

/** Deterministic order, so a re-import of the same export is a no-op diff. */
function ordered(products) {
  return [...products].sort(
    (a, b) =>
      String(a.cartridge).localeCompare(String(b.cartridge)) ||
      String(a.brand).localeCompare(String(b.brand)) ||
      String(a.line).localeCompare(String(b.line)) ||
      String(a.id).localeCompare(String(b.id)),
  );
}

function serialize(products) {
  const body = products
    .map((product) => {
      const fields = Object.entries(product).map(
        ([key, value]) => `    ${key}: ${JSON.stringify(value)},`,
      );
      return `  {\n${fields.join('\n')}\n  },`;
    })
    .join('\n');
  return `// Generated by tools/import-products.mjs. Do not edit by hand.
// Import an export with: node tools/import-products.mjs <catalog.csv|json>
export const PRODUCT_SCHEMA_VERSION = ${PRODUCT_SCHEMA_VERSION};

/** Box sizes a price may refer to, so per-round maths stays honest. */
export const PACKAGE_SIZES = ${JSON.stringify(PACKAGE_SIZES)};

export const PRODUCTS = [
${body}
];
`;
}

const args = process.argv.slice(2);
const flags = new Set(args.filter((argument) => argument.startsWith('--')));
const path = args.find((argument) => !argument.startsWith('--'));

if (!path) {
  console.error('Usage: node tools/import-products.mjs <catalog.csv|json> [--check] [--dry-run]');
  process.exit(2);
}

const incoming = readCatalog(resolve(path));
const problems = validateProducts(incoming);
const stats = {
  products: incoming.length,
  cartridges: new Set(incoming.map((product) => product.cartridge)).size,
  brands: new Set(incoming.map((product) => product.brand)).size,
  priced: incoming.filter((product) => product.priceUsd != null).length,
};

if (problems.length) {
  console.error(`✗ ${problems.length} problem(s) in ${path}:`);
  for (const problem of problems) console.error(`  ${problem}`);
  process.exit(1);
}

const text = serialize(ordered(incoming));
console.error(
  `✓ ${stats.products} products · ${stats.cartridges} cartridges · ${stats.brands} brands · ${stats.priced} priced`,
);

if (flags.has('--dry-run')) {
  console.error('(dry run, nothing written)');
  process.exit(0);
}

if (flags.has('--check')) {
  const current = readFileSync(OUT, 'utf8');
  if (current !== text) {
    const before = new Set(PRODUCTS.map((product) => product.id));
    const after = new Set(incoming.map((product) => product.id));
    const added = [...after].filter((id) => !before.has(id));
    const removed = [...before].filter((id) => !after.has(id));
    console.error(
      `✗ data/products.js is stale — ${added.length} added, ${removed.length} removed` +
        `${added.length ? ` (e.g. ${added.slice(0, 3).join(', ')})` : ''}`,
    );
    process.exit(1);
  }
  console.error('✓ data/products.js is up to date');
  process.exit(0);
}

writeFileSync(OUT, text);
console.error('✓ wrote data/products.js');
