#!/usr/bin/env node
// Generates docs/tracklist.md from the pinned Deezer snapshot in data/.
// The running order is curated (see PROGRAM below); durations and links are
// pulled from the snapshot so the runtime math can never drift from the source.
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SNAPSHOT = path.join(ROOT, 'data', 'deezer-top-60.json');
const OUT = path.join(ROOT, 'docs', 'tracklist.md');

// Red Book limit for an 80-minute CD-R is 79:57.
const CD_LIMIT_SECONDS = 79 * 60 + 57;

// Ordered program: [deezer title, album override]. Album clears to the
// studio album when Deezer reports the single release instead.
const PROGRAM = [
  ['Tough (feat. Noah Kahan)', null],
  ['Straightjacket', null],
  ['Stacy', null],
  ['A Letter To My Younger Self', 'A Letter to My Younger Self'],
  ['FFYL', null],
  ['Too Late', 'The People’s Champ'],
  ['Autopilot', null],
  ['Flare Guns (feat. Chelsea Cutler)', null],
  ['Best Day', null],
  ['Pasadena', null],
  ['BULL IN A CHINA SHOP', null],
  ['Sober Up', null],
  ['Am I High Rn (feat. blackbear)', null],
  ['Bartender', 'The People’s Champ'],
  ['Yellow Brick Road', null],
  ['Werewolf (feat. Yoshi Flower)', null],
  ['My Wife & 2 Dogs', 'Change of Scenery II'],
  ['Common', 'The People’s Champ'],
  ['Olive Tree', null],
  ['Another Day in Paradise', 'Change of Scenery'],
  // Co-leads and features, kept as a closing block so the CD reads as
  // "his songs, then the collabs".
  ['Love Me Less (feat. Quinn XCII)', null],
  ['Kings of Summer (Single Version)', null],
  ['Little Things', null],
  ['U & Us', null],
];

const snapshot = JSON.parse(fs.readFileSync(SNAPSHOT, 'utf8'));
const byTitle = new Map(snapshot.tracks.map((t) => [t.title, t]));

const fmt = (s) => `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;

let cumulative = 0;
const missing = [];
const rows = PROGRAM.map(([title, albumOverride], i) => {
  const hit = byTitle.get(title);
  if (!hit) {
    missing.push(title);
    return null;
  }
  cumulative += hit.duration;
  const album = albumOverride ?? hit.album;
  const credit = hit.artist === 'Quinn XCII' ? '' : ` *(${hit.artist})*`;
  return `| ${i + 1} | ${title}${credit} | ${album} | ${fmt(hit.duration)} | ${fmt(cumulative)} | [link](${hit.link}) |`;
});

if (missing.length) {
  console.error(`Titles not found in snapshot: ${missing.join(', ')}`);
  process.exit(1);
}

if (cumulative > CD_LIMIT_SECONDS) {
  console.error(
    `Program is ${fmt(cumulative)} — over the ${fmt(CD_LIMIT_SECONDS)} CD limit.`,
  );
  process.exit(1);
}

const doc = `# Quinn XCII — most popular, CD running order

Generated by \`scripts/build_tracklist.js\` from \`data/deezer-top-60.json\`
(Deezer "top tracks" for artist 9036740, fetched 2026-10-20). Deezer's top
ordering is the popularity signal; the \`rank\` column in the snapshot is
Deezer's global track score and is used only as a tiebreaker.

**${PROGRAM.length} tracks — ${fmt(cumulative)} total.** CD-R ceiling is
${fmt(CD_LIMIT_SECONDS)}, so there is ${fmt(CD_LIMIT_SECONDS - cumulative)} of
headroom on an 80-minute disc.

| # | Track | Album | Time | Cumulative | Ref |
|---|-------|-------|------|-----------|-----|
${rows.join('\n')}

Credits marked *(artist)* are co-leads/features rather than Quinn XCII solo
tracks. They sit in a closing block so the disc plays as solo material first.

## Alternates (swap in if you want a different feel)

Pulled from the same snapshot, next most popular by Deezer ordering:

| Track | Album | Time |
|-------|-------|------|
| Stay Next To Me (with Chelsea Cutler) | Stay Next To Me | 3:26 |
| Two 10s | Two 10s | 3:36 |
| HOOPLA | HOOPLA | 2:14 |
| Georgia Peach | The People’s Champ (Extended Version) | 2:21 |
| Coffee | Coffee | 3:00 |
| Melt | Melt | 3:32 |
| Monday Morning | Change of Scenery II | 2:32 |
| Candle | The Story of Us (Deluxe) | 3:34 |

## Where to get the audio

Buy or stream-rip from a licensed source, then drop the files in \`audio/\`:

- Bandcamp — https://quinnxcii.bandcamp.com
- Apple Music / iTunes Store (purchased AAC or ALAC)
- Amazon Music (MP3 store)
- Qobuz (lossless)

The burn script transcodes to Red Book WAV, so lossless sources (ALAC/FLAC) give
the cleanest disc; 256k+ AAC/MP3 is fine too.
`;

fs.writeFileSync(OUT, doc);
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${PROGRAM.length} tracks, ${fmt(cumulative)}`);
