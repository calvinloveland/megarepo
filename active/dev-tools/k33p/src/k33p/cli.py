"""CLI entry point for k33p.

Subcommands:

- ``k33p init``   — create a new k33p project
- ``k33p clone``   — clone a project from a local directory
- ``k33p sync``    — pull updates for the current project
- ``k33p import``  — import an external project (git, etc.)
- ``k33p daemon`` — run the auto-commit daemon
- ``k33p pointer`` — manage live channel pointers
- ``k33p org``     — manage permissions and access
- ``k33p split``   — split a subproject into a standalone project
- ``k33p convert`` — convert project to another format (WIP)
- ``k33p lock verify <path>`` — verify lockfile signature
- ``k33p tui``    — launch the TUI viewer
- ``k33p info``   — print project info and exit
- ``k33p store``  — content-addressed store operations
- ``k33p version``— print version and exit

When no subcommand is given, the first positional argument is treated as a
path and the TUI is launched (backward-compatible with ``k33p <path>``).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

SUBCOMMANDS = frozenset({"init", "clone", "sync", "import", "daemon", "tui", "info", "store", "pointer", "org", "split", "convert", "lock", "serve", "get", "version"})


# ── subcommand handlers (defined here, dispatched from main) ──────────────


def _cmd_init(args: list[str]) -> int:
    """``k33p init`` — create a new k33p project."""
    parser = argparse.ArgumentParser(
        prog="k33p init",
        description="Create a new k33p project",
    )
    parser.add_argument("name", help="Project name")
    parser.add_argument(
        "--dir", "-d",
        default=".",
        help="Directory to create the project in (default: current dir)",
    )
    parser.add_argument(
        "--description", "-m",
        default="",
        help="Short project description",
    )
    parser.add_argument(
        "--org", default=None,
        help="Organisation or namespace",
    )
    parser.add_argument(
        "--type",
        default="single",
        choices=("single", "monorepo"),
        help="Project type (default: single)",
    )
    parser.add_argument(
        "--force", "-f",
        action="store_true",
        help="Overwrite existing k33p.yaml if present",
    )
    parsed = parser.parse_args(args)

    target = Path(parsed.dir).resolve()
    yaml_path = target / "k33p.yaml"

    if yaml_path.exists() and not parsed.force:
        print(f"k33p: {yaml_path} already exists (use --force to overwrite)",
              file=sys.stderr)
        return 1

    name = parsed.name

    # Build a minimal k33p.yaml
    channels = f"""\
  src:
    type: source
    transport: git+https://example.com/{name}
    visibility: public
    history: full
"""

    yaml_lines = [f"# k33p.yaml — generated by `k33p init`"]
    yaml_lines.append(f"project: {name}")
    yaml_lines.append(f"type: {parsed.type}")
    if parsed.description:
        yaml_lines.append(f"description: {parsed.description}")
    if parsed.org:
        yaml_lines.append(f"org: {parsed.org}")
    yaml_lines.append("")
    yaml_lines.append("channels:")
    yaml_lines.append(channels)
    yaml_lines.append("views:")
    yaml_lines.append("  default:")
    yaml_lines.append("    src: { at: \"./\" }")
    yaml_lines.append("")
    yaml_lines.append("roles:")
    yaml_lines.append("  developer:   { view: default }")
    yaml_lines.append("")

    yaml_content = "\n".join(yaml_lines)

    target.mkdir(parents=True, exist_ok=True)
    yaml_path.write_text(yaml_content, encoding="utf-8")

    # Initialise the store
    store_path = target / ".k33p" / "store"
    store_path.mkdir(parents=True, exist_ok=True)
    (target / ".k33p" / ".gitkeep").write_text("")
    (target / ".k33p" / "store" / ".gitkeep").write_text("")

    print(f"✓ Initialised k33p project {name!r} at {target}")
    print(f"  manifest: {yaml_path}")
    print(f"  store:    {store_path}")
    print(f"  type:     {parsed.type}")
    print()
    print("Next steps:")
    print(f"  cd {target}")
    print("  k33p             # launch the TUI viewer")
    print("  k33p info        # show project info")
    return 0


def _cmd_tui(args: list[str]) -> int:
    """``k33p tui`` — launch the TUI viewer."""
    parser = argparse.ArgumentParser(
        prog="k33p tui",
        description="Launch the TUI viewer",
    )
    parser.add_argument(
        "path",
        nargs="?",
        default=".",
        help="Path to project directory or k33p.yaml (default: .)",
    )
    parser.add_argument(
        "--subproject", "-s", default=None,
        help="Subproject to focus on (monorepo only)",
    )
    parser.add_argument(
        "--role", "-r", default=None,
        help="Role to use (default: from manifest)",
    )
    parsed = parser.parse_args(args)

    from k33p.project import load_project

    try:
        project = load_project(parsed.path)
    except FileNotFoundError as e:
        print(f"k33p: {e}", file=sys.stderr)
        return 2
    except Exception as e:
        print(f"k33p: failed to load project: {e}", file=sys.stderr)
        return 1

    if parsed.subproject:
        project.set_subproject(parsed.subproject)
    if parsed.role:
        project.set_role(parsed.role)

    from k33p.tui.app import K33pApp

    app = K33pApp(project)
    app.run()
    return 0


