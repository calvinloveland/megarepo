def _cmd_lock(args: list[str]) -> int:
    """``k33p lock`` — lockfile operations."""
    if not args:
        print("k33p lock: expected a subcommand (verify)", file=sys.stderr)
        return 2

    sub = args[0]
    rest = args[1:]

    if sub == "verify":
        parser = argparse.ArgumentParser(prog="k33p lock verify")
        parser.add_argument(
            "path",
            nargs="?",
            default=".",
            help="Path to k33p.lock or project directory (default: .)",
        )
        parser.add_argument(
            "--key", default=None,
            help="Path to public key file",
        )
        parsed = parser.parse_args(rest)

        # Resolve the lock file path
        lock_path = Path(parsed.path)
        if lock_path.is_dir():
            lock_path = lock_path / "k33p.lock"
        if not lock_path.exists():
            print(f"k33p: lock file not found: {lock_path}", file=sys.stderr)
            return 1

        from k33p.sig import verify_lock_signature, VerifyError

        try:
            valid, msg = verify_lock_signature(lock_path, key_path=parsed.key)
        except VerifyError as e:
            print(f"k33p: {e}", file=sys.stderr)
            return 1

        if valid:
            print(f"{lock_path}: {msg}")
            return 0
        else:
            print(f"{lock_path}: {msg}", file=sys.stderr)
            return 1

    print(f"k33p lock: unknown subcommand {sub!r}", file=sys.stderr)
    return 2


def _cmd_serve(args: list[str]) -> int:
    """``k33p serve`` — start HTTP server to share store objects."""
    parser = argparse.ArgumentParser(
        prog="k33p serve",
        description="Start an HTTP server to share store objects with peers",
    )
    parser.add_argument(
        "path",
        nargs="?",
        default=".",
        help="Path to the project (default: .)",
    )
    parser.add_argument(
        "--host", default="127.0.0.1",
        help="Host to bind to (default: 127.0.0.1)",
    )
    parser.add_argument(
        "--port", "-p", type=int, default=8734,
        help="Port to listen on (default: 8734)",
    )
    parsed = parser.parse_args(args)

    from k33p.project import load_project

    try:
        project = load_project(parsed.path)
    except FileNotFoundError as e:
        print(f"k33p: {e}", file=sys.stderr)
        return 1
    except Exception as e:
        print(f"k33p: {e}", file=sys.stderr)
        return 1

    from k33p.transport_k33p import serve_store
    store_path = project.store_path or (project.path / ".k33p" / "store")
    serve_store(store_path, host=parsed.host, port=parsed.port)
    return 0


