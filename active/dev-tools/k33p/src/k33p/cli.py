def _cmd_store(args: list[str]) -> int:
    """``k33p store`` — CAS operations."""
    if not args:
        print("k33p store: expected a subcommand (put, get, stats, ls)",
              file=sys.stderr)
        return 2

    store_cmd = args[0]
    rest = args[1:]

    from k33p.store import ContentStore

    if store_cmd == "put":
        parser = argparse.ArgumentParser(prog="k33p store put")
        parser.add_argument("path", help="Path to the project")
        parser.add_argument("file", help="Path to the file to store")
        parser.add_argument(
            "--kind", "-k", default="blob",
            help="Object kind (default: blob)",
        )
        parsed = parser.parse_args(rest)
        return _do_store_put(parsed, ContentStore)

    if store_cmd == "get":
        parser = argparse.ArgumentParser(prog="k33p store get")
        parser.add_argument("path", help="Path to the project")
        parser.add_argument("hash", help="SHA-256 hash of the object")
        parsed = parser.parse_args(rest)
        return _do_store_get(parsed, ContentStore)

    if store_cmd == "stats":
        parser = argparse.ArgumentParser(prog="k33p store stats")
        parser.add_argument("path", help="Path to the project")
        parsed = parser.parse_args(rest)
        return _do_store_stats(parsed, ContentStore)

    if store_cmd == "ls":
        parser = argparse.ArgumentParser(prog="k33p store ls")
        parser.add_argument("path", help="Path to the project")
        parsed = parser.parse_args(rest)
        return _do_store_ls(parsed, ContentStore)

    if store_cmd == "verify":
        parser = argparse.ArgumentParser(prog="k33p store verify")
        parser.add_argument("path", help="Path to the project")
        parsed = parser.parse_args(rest)
        return _do_store_verify(parsed, ContentStore)

    if store_cmd == "gc":
        parser = argparse.ArgumentParser(prog="k33p store gc")
        parser.add_argument("path", help="Path to the project")
        parser.add_argument(
            "--dry-run", "-n",
            action="store_true",
            help="Only report what would be removed, do not delete",
        )
        parsed = parser.parse_args(rest)
        return _do_store_gc(parsed, ContentStore)

    print(f"k33p store: unknown subcommand {store_cmd!r} "
          f"(choose from put, get, stats, ls, verify, gc)",
          file=sys.stderr)
    return 2


# ── store sub-subcommand implementations ────────────────────────────────


def _get_store(parsed_path: str, ContentStore_cls: type) -> tuple:
    """Load a project and return (ContentStore, project)."""
    from k33p.project import load_project

    try:
        project = load_project(parsed_path)
    except FileNotFoundError as e:
        print(f"k33p: {e}", file=sys.stderr)
        return None, None
    except Exception as e:
        print(f"k33p: {e}", file=sys.stderr)
        return None, None

    store_path = project.store_path or project.path / ".k33p" / "store"
    store = ContentStore_cls(store_path)
    return store, project


def _do_store_put(
    parsed: argparse.Namespace, ContentStore_cls: type,
) -> int:
    store, project = _get_store(parsed.path, ContentStore_cls)
    if store is None:
        return 2

    file_path = Path(parsed.file)
    if not file_path.exists():
        print(f"k33p: file not found: {file_path}", file=sys.stderr)
        return 1
    data = file_path.read_bytes()
    kind = parsed.kind
    hash_str = store.put(data, kind=kind)
    print(f"Stored as {hash_str}  ({kind}, {len(data)} bytes uncompressed)")
    return 0


def _do_store_get(
    parsed: argparse.Namespace, ContentStore_cls: type,
) -> int:
    store, project = _get_store(parsed.path, ContentStore_cls)
    if store is None:
        return 2

    data = store.get(parsed.hash)
    if data is None:
        print(f"k33p: object not found: {parsed.hash}", file=sys.stderr)
        return 1
    kind = store.get_kind(parsed.hash)
    print(f"# kind={kind}  size={len(data)}")
    sys.stdout.buffer.write(data)
    if data and data[-1:] != b"\n":
        sys.stdout.buffer.write(b"\n")
    return 0


def _do_store_stats(
    parsed: argparse.Namespace, ContentStore_cls: type,
) -> int:
    store, project = _get_store(parsed.path, ContentStore_cls)
    if store is None:
        return 2

    stats = store.stats()
    mb_comp = stats.compressed_bytes / 1024 / 1024
    mb_uncomp = stats.total_bytes / 1024 / 1024
    print(f"Objects:   {stats.object_count}")
    print(f"Size:      {mb_uncomp:.2f} MB uncompressed, "
          f"{mb_comp:.2f} MB on disk")
    print(f"Shards:    {stats.shard_count}")
    if stats.object_count > 0:
        avg = stats.total_bytes / stats.object_count
        print(f"Avg obj:   {avg:.0f} bytes")
    return 0


def _do_store_ls(
    parsed: argparse.Namespace, ContentStore_cls: type,
) -> int:
    store, project = _get_store(parsed.path, ContentStore_cls)
    if store is None:
        return 2

    print(f"{'Hash':64}  {'Kind':12}  {'Size':>8}")
    print("-" * 88)
    for obj in store.iter_objects():
        print(f"{obj.hash:64}  {obj.kind:12}  {obj.size:>8}")
    return 0


def _do_store_verify(
    parsed: argparse.Namespace, ContentStore_cls: type,
) -> int:
    store, project = _get_store(parsed.path, ContentStore_cls)
    if store is None:
        return 2

    result = store.verify()
    print(f"Verification complete:")
    print(f"  total:     {result.total}")
    print(f"  ok:        {result.ok}")
    print(f"  corrupted: {result.corrupted}")
    if result.errors:
        print(f"\nErrors ({len(result.errors)}):")
        for err in result.errors[:10]:
            print(f"  • {err}")
        if len(result.errors) > 10:
            print(f"  ... and {len(result.errors) - 10} more")
        return 1
    return 0


def _do_store_gc(
    parsed: argparse.Namespace, ContentStore_cls: type,
) -> int:
    store, project = _get_store(parsed.path, ContentStore_cls)
    if store is None:
        return 2

    removed = store.gc(dry_run=parsed.dry_run)
    if parsed.dry_run:
        print(f"GC dry-run: {removed} object(s) would be removed")
        if removed == 0:
            print("Store is clean.")
    else:
        print(f"GC complete: {removed} object(s) removed")
        if removed == 0:
            print("Store is clean.")
    return 0


# ── main dispatcher ─────────────────────────────────────────────────────


def main(argv: list[str] | None = None) -> int:
    """Run the k33p CLI.

    Manual dispatch to avoid argparse subparser complications, and to
    preserve backward compatibility: ``k33p <path>`` launches the TUI.
    """
    args = list(argv) if argv is not None else sys.argv[1:]

    if args and args[0] in SUBCOMMANDS:
        cmd = args[0]
        rest = args[1:]
    else:
        cmd = "tui"  # default (backward compat)
        rest = args   # ``k33p <path>`` → rest = [path]

    dispatch = {
        "init": _cmd_init,
        "clone": _cmd_clone,
        "sync": _cmd_sync,
        "import": _cmd_import,
        "daemon": _cmd_daemon,
        "tui": _cmd_tui,
        "info": _cmd_info,
        "store": _cmd_store,
        "pointer": _cmd_pointer,
        "org": _cmd_org,
        "split": _cmd_split,
        "convert": _cmd_convert,
        "lock": _cmd_lock,
        "serve": _cmd_serve,
        "get": _cmd_get,
        "version": _cmd_version,
    }

    handler = dispatch.get(cmd)
    if handler is None:
        print(f"k33p: unknown command {cmd!r}", file=sys.stderr)
        return 2
    return handler(rest)


